export const supportedLanguages = ['ha', 'en'];

export function getTranslationKeys(language) {
  return Object.keys(messages[language] ?? {}).sort();
}

export function getInterfaceContentLanguage(language) {
  return getLanguage(language)?.interfaceTranslationAvailable ? language : 'en';
}

export function createLocale(storage = globalThis.localStorage) {
  let language = 'ha';
  try {
    const saved = storage?.getItem('mkbot-language');
    if (getLanguage(saved)) language = normalizeLanguageCode(saved);
  } catch {
    // Keep Hausa as the default when browser storage is unavailable.
  }

  return {
    get language() {
      return language;
    },
    get direction() {
      return getLanguage(language)?.direction ?? 'ltr';
    },
    setLanguage(nextLanguage) {
      const normalized = normalizeLanguageCode(nextLanguage);
      if (!normalized) return false;
      language = normalized;
      try {
        storage?.setItem('mkbot-language', language);
      } catch {
        // Language still changes for this page session.
      }
      return true;
    },
    t(key) {
      return messages[language]?.[key] ?? messages.en[key] ?? key;
    },
  };
}